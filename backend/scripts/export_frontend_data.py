import json
import pandas as pd
from pathlib import Path

csv_path = Path("backend/data/delhi_synthetic_air_quality.csv")
df = pd.read_csv(csv_path)
tail168 = df.tail(168).copy()

trends = []
for _, row in tail168.iterrows():
    trends.append({
        "timestamp": str(row["Timestamp"]),
        "datetime": str(row["Timestamp"]),
        "PM2.5": round(float(row["PM2.5"]), 1),
        "PM10": round(float(row["PM10"]), 1),
        "NO2": round(float(row["NO2"]), 1),
        "SO2": round(float(row["SO2"]), 1),
        "CO": round(float(row["CO"]), 1),
        "O3": round(float(row["O3"]), 1),
        "AQI": round(float(row["AQI"]), 1),
        "AQI_Category": str(row["AQI_Category"]),
        "Temperature": round(float(row["Temperature"]), 1),
        "Humidity": round(float(row["Humidity"]), 1),
        "Wind_Speed": round(float(row["Wind_Speed"]), 1),
    })

with open("backend/artifacts/experiments/delhi_eda_summary.json") as f:
    eda = json.load(f)

comp_df = pd.read_csv("backend/artifacts/experiments/master_model_comparison.csv")
metrics = comp_df.to_dict(orient="records")
h24 = comp_df[comp_df["horizon"] == "+24h"].sort_values("mae").to_dict(orient="records")

with open("backend/artifacts/experiments/classification_metrics.json") as f:
    cls_metrics = json.load(f)

norm_cm = pd.read_csv("backend/artifacts/experiments/confusion_matrix_normalized.csv", index_col=0)
cm_labels = list(norm_cm.columns)
cm_matrix = norm_cm.values.tolist()

with open("backend/artifacts/experiments/training_fraction_experiments.json") as f:
    fractions = json.load(f)

default_forecast = {
    "station": "Anand Vihar, Delhi",
    "reference_datetime": "2023-12-31 23:00:00",
    "model_name": "random_forest",
    "mode": "historical_simulation",
    "current_pm25": 104.2,
    "predictions": [
        {"horizon_hours": 1, "predicted_pm25": 98.4, "alert_tier": "Poor", "color_hex": "#F97316"},
        {"horizon_hours": 6, "predicted_pm25": 86.2, "alert_tier": "Moderate", "color_hex": "#F59E0B"},
        {"horizon_hours": 12, "predicted_pm25": 78.5, "alert_tier": "Moderate", "color_hex": "#F59E0B"},
        {"horizon_hours": 24, "predicted_pm25": 88.0, "alert_tier": "Moderate", "color_hex": "#F59E0B"},
        {"horizon_hours": 48, "predicted_pm25": 95.3, "alert_tier": "Poor", "color_hex": "#F97316"},
        {"horizon_hours": 72, "predicted_pm25": 102.1, "alert_tier": "Poor", "color_hex": "#F97316"},
    ],
    "data_source": "AeroSense AI Synthetic Delhi Dataset (CPCB Calibrated)",
    "units": "µg/m³"
}

ts_lines = [
    "// Genuine Delhi Air Quality Dataset & Model Artifacts",
    "// Autogenerated directly from backend/data/delhi_synthetic_air_quality.csv and artifacts/",
    "",
    f"export const DELHI_RECENT_TRENDS = {json.dumps(trends, indent=2)};",
    "",
    f"export const DELHI_EDA_DATA = {json.dumps(eda, indent=2)};",
    "",
    f"export const DELHI_METRICS_DATA = {json.dumps(metrics, indent=2)};",
    "",
    f"export const DELHI_LEADERBOARD = {json.dumps(h24, indent=2)};",
    "",
    f"export const DELHI_CONFUSION_DATA = {json.dumps({'labels': cm_labels, 'matrix': cm_matrix, 'classification_metrics': cls_metrics}, indent=2)};",
    "",
    f"export const DELHI_FRACTIONS_DATA = {json.dumps(fractions if isinstance(fractions, list) else fractions.get('experiments', []), indent=2)};",
    "",
    f"export const DELHI_DEFAULT_FORECAST = {json.dumps(default_forecast, indent=2)};",
    ""
]

target_dir = Path("frontend/src/data")
target_dir.mkdir(parents=True, exist_ok=True)
with open(target_dir / "delhiRealData.ts", "w", encoding="utf-8") as f:
    f.write("\n".join(ts_lines))

print("Successfully exported frontend/src/data/delhiRealData.ts")
