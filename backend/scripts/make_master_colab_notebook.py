                "# ─── 6. DEEP SEQUENTIAL MODELS (LSTM & CNN-LSTM HYBRID) ───────────────────────\n",
                "import torch.nn as nn\n",
                "from torch.utils.data import TensorDataset, DataLoader\n",
                "\n",
                "def create_temporal_sequences(X, y, seq_len=14):\n",
                "    xs, ys = [], []\n",
                "    for i in range(len(X) - seq_len + 1):\n",
                "        xs.append(X[i:i+seq_len])\n",
                "        ys.append(y[i+seq_len-1])\n",
                "    return np.array(xs, dtype=np.float32), np.array(ys, dtype=np.float32)\n",
                "\n",
                "SEQ_LEN = 14\n",
                "X_sq_tr, y_sq_tr = create_temporal_sequences(s_del['X_tr'], s_del['y_tr'], SEQ_LEN)\n",
                "X_sq_va, y_sq_va = create_temporal_sequences(s_del['X_va'], s_del['y_va'], SEQ_LEN)\n",
                "X_sq_te, y_sq_te = create_temporal_sequences(s_del['X_te'], s_del['y_te'], SEQ_LEN)\n",
                "y_sq_te_base = s_del['y_te_base'][SEQ_LEN-1:]\n",
                "\n",
                "tr_loader = DataLoader(TensorDataset(torch.tensor(X_sq_tr), torch.tensor(y_sq_tr)), batch_size=32, shuffle=True)\n",
                "criterion = nn.MSELoss()\n",
                "\n",
                "# Model 1: Standard LSTM Forecaster\n",
                "class LSTMForecaster(nn.Module):\n",
                "    def __init__(self, in_dim, h_dim=64, num_layers=2, horizons=6):\n",
                "        super().__init__()\n",
                "        self.lstm = nn.LSTM(in_dim, h_dim, num_layers=num_layers, batch_first=True, dropout=0.2)\n",
                "        self.fc = nn.Linear(h_dim, horizons)\n",
                "    def forward(self, x):\n",
                "        out, _ = self.lstm(x)\n",
                "        return self.fc(out[:, -1, :])\n",
                "\n",
                "lstm = LSTMForecaster(len(feat_cols), hidden_dim=64 if 'hidden_dim' in locals() else 64, horizons=6).to(device)\n",
                "opt_lstm = torch.optim.AdamW(lstm.parameters(), lr=1e-3, weight_decay=1e-4)\n",
                "\n",
                "print('Training Standard LSTM...')\n",
                "for ep in range(15):\n",
                "    lstm.train()\n",
                "    for bx, by in tr_loader:\n",
                "        bx, by = bx.to(device), by.to(device)\n",
                "        opt_lstm.zero_grad()\n",
                "        loss = criterion(lstm(bx), by)\n",
                "        loss.backward()\n",
                "        opt_lstm.step()\n",
                "\n",
                "lstm.eval()\n",
                "with torch.no_grad():\n",
                "    y_pred_lstm = lstm(torch.tensor(X_sq_te).to(device)).cpu().numpy()\n",
                "evaluate_model_horizons(y_sq_te, y_pred_lstm, y_sq_te_base, 'delhi', 'Standard LSTM')\n",
                "torch.save(lstm.state_dict(), MODELS_DIR / 'lstm_delhi.pt')\n",
                "torch.save(lstm.state_dict(), MODELS_DIR / 'lstm_model.pt')\n",
                "print('[✓] Trained & saved lstm_delhi.pt')\n",
                "\n",
                "# Model 2: CNN-LSTM Hybrid Forecaster\n",
                "class CNNLSTMForecaster(nn.Module):\n",
                "    def __init__(self, in_dim, h_dim=64, horizons=6):\n",
                "        super().__init__()\n",
                "        self.conv = nn.Conv1d(in_channels=in_dim, out_channels=32, kernel_size=3, padding=1)\n",
                "        self.relu = nn.ReLU()\n",
                "        self.lstm = nn.LSTM(32, h_dim, num_layers=2, batch_first=True, dropout=0.2)\n",
                "        self.fc = nn.Linear(h_dim, horizons)\n",
                "    def forward(self, x):\n",
                "        cx = self.relu(self.conv(x.transpose(1, 2))).transpose(1, 2)\n",
                "        out, _ = self.lstm(cx)\n",
                "        return self.fc(out[:, -1, :])\n",
                "\n",
                "cnn_lstm = CNNLSTMForecaster(len(feat_cols), horizons=6).to(device)\n",
                "opt_cnn = torch.optim.AdamW(cnn_lstm.parameters(), lr=1e-3, weight_decay=1e-4)\n",
                "\n",
                "print('Training CNN-LSTM Hybrid...')\n",
                "for ep in range(15):\n",
                "    cnn_lstm.train()\n",
                "    for bx, by in tr_loader:\n",
                "        bx, by = bx.to(device), by.to(device)\n",
                "        opt_cnn.zero_grad()\n",
                "        loss = criterion(cnn_lstm(bx), by)\n",
                "        loss.backward()\n",
                "        opt_cnn.step()\n",
                "\n",
